UI::UI(Renderer* r, Input* input) : r_(r), in_(input) {}

void UI::begin(const Mat4& pv, float ox, float oy, float hw, float hh) {
  pv_ = pv;
  ox_ = ox;
  oy_ = oy;
  hw_ = hw;
  hh_ = hh;
  begun_ = true;
  r_->use_program(ProgramKind::Unlit);
  r_->set_depth_test(false);
  r_->set_blend(true);
  r_->bind_texture(0);
}

void UI::end() { begun_ = false; }

void UI::quad_px(float x, float y, float w, float h, const Vec4& color) {
  if (!begun_) return;
  // UI pixel space (origin at viewport top-left, y down) -> 2D camera world
  // space (origin at viewport center, y up), 1 px = 1 unit.
  float wx = x + w * 0.5f - hw_;
  float wy = hh_ - (y + h * 0.5f);
  Mat4 model = Mat4::translation({wx, wy, 0.0f}) * Mat4::scaling({w, h, 1});
  r_->set_matrix("proj", Mat4::identity());
  r_->set_matrix("view", pv_);
  r_->set_matrix("model", model);
  Material m;
  m.baseColor = color;
  r_->set_material(m);
  r_->draw(r_->builtin_quad());
}

float UI::text_width(const std::string& s, float px) const {
  float u = px / 7.0f;
  return (float)s.size() * 6.0f * u;
}

void UI::text(const std::string& s, float x, float y, float px, const Vec4& color) {
  if (!begun_) return;
  float u = px / 7.0f;  // pixel size of one font cell
  std::vector<float> verts;
  std::vector<uint32_t> idx;
  for (size_t ci = 0; ci < s.size(); ++ci) {
    unsigned char c = (unsigned char)s[ci];
    if (c < 32 || c > 126) c = 32;
    const uint8_t* glyph = kFont[c - 32];
    float gx = x + (float)ci * 6.0f * u;
    for (int row = 0; row < 5; ++row) {
      uint8_t bits = glyph[row];
      for (int col = 0; col < 5; ++col) {
        if (!(bits & (0x10 >> col))) continue;
        // pixel rect -> world rect (1px = 1 unit, y flipped)
        float x0 = gx + col * u - hw_;
        float x1 = gx + (col + 1) * u - hw_;
        float y0 = hh_ - (y + (row + 1) * u);
        float y1 = hh_ - (y + row * u);
        uint32_t base = (uint32_t)verts.size() / 8;
        const float q[4][2] = {{x0, y0}, {x1, y0}, {x1, y1}, {x0, y1}};
        for (int k = 0; k < 4; ++k)
          verts.insert(verts.end(), {q[k][0], q[k][1], 0, 0, 0, 1, 0, 0});
        idx.insert(idx.end(), {base, base + 1, base + 2, base, base + 2, base + 3});
      }
    }
  }
  if (idx.empty()) return;
  Renderer::Mesh mesh{verts.data(), (int)verts.size() / 8, idx.data(), (int)idx.size()};
  r_->set_matrix("proj", Mat4::identity());
  r_->set_matrix("view", pv_);
  r_->set_matrix("model", Mat4::identity());
  Material m;
  m.baseColor = color;
  r_->set_material(m);
  MeshId id = r_->create_mesh(mesh);
  r_->draw(id);
  r_->destroy_mesh(id);  // safe: draw() has consumed the data
}

void UI::rect(float x, float y, float w, float h, const Vec4& color) {
  quad_px(x, y, w, h, color);
}

void UI::panel(float x, float y, float w, float h, const Vec4& bg, const Vec4& border) {
  quad_px(x, y, w, h, bg);
  quad_px(x, y, w, 1.0f, border);
  quad_px(x, y + h - 1.0f, w, 1.0f, border);
  quad_px(x, y, 1.0f, h, border);
  quad_px(x + w - 1.0f, y, 1.0f, h, border);
}

bool UI::button(const std::string& label, float x, float y, float w, float h, const Vec4& idle,
                const Vec4& hover, float text_px) {
  Vec2 m = in_->mouse() - Vec2{ox_, oy_};
  bool hot = m.x >= x && m.x < x + w && m.y >= y && m.y < y + h;
  quad_px(x, y, w, h, hot ? hover : idle);
  quad_px(x, y, w, 1.0f, {0.3f, 0.35f, 0.5f, 1.0f});
  quad_px(x, y + h - 1.0f, w, 1.0f, {0.3f, 0.35f, 0.5f, 1.0f});
  float tw = text_width(label, text_px);
  text(label, x + (w - tw) * 0.5f, y + (h - text_px) * 0.5f, text_px,
       Vec4{0.92f, 0.95f, 1.0f, 1.0f});
  return hot && in_->mouse_pressed(MouseButton::Left);
}

void UI::bar(float x, float y, float w, float h, float frac, const Vec4& fg, const Vec4& bg) {
  quad_px(x, y, w, h, bg);
  quad_px(x, y, w * math::clampf(frac, 0.0f, 1.0f), h, fg);
}

